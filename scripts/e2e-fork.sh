#!/usr/bin/env bash
# KUB Stake — mainnet-FORK end-to-end test (T11, optional): proves the worker's REAL tx path
# (sign → persist → broadcast → receipt → event decode → DB) on a local anvil fork of KUB mainnet,
# with zero real funds:
#
#   npm run e2e:fork        (= bash scripts/e2e-fork.sh) — needs Docker + `npm install` at the repo root
#
# Isolation: separate compose project "kubstake-e2e" (own volume kubstake-e2e_pgdata, own network, own
# image tag kubstake-worker:e2e), own generated secrets file scripts/e2e-fork/.env.e2e (gitignored,
# deleted on exit), web not started. Your .env, your stack and the kubstake_pgdata volume are not used.
#
# SAFETY: this worker always signs and broadcasts, so (a) the overlay pins its RPC_URL to http://anvil:8545
# (a literal, not interpolated), (b) this script refuses to start unless the resolved compose config says
# so, (c) it checks the worker's own startup log line, and (d) setup.ts/assert.ts refuse any RPC that is not
# an anvil node on 127.0.0.1. The wallet is a freshly generated key funded only on the fork (anvil_setBalance).
#
# Flow: .env.e2e → guard → build worker image → db + migrate → anvil fork (started LAST: the upstream RPC is
# not an archive node, so the forked block's state stops being served after ~128 blocks ≈ 6 min) → seed →
# worker → flow (delegate, reward, compound, auto-compound, claim, undelegate) → assert → E2E OK.
# Always cleans up (trap EXIT): docker compose down -v + rm .env.e2e.
#
# Knobs: E2E_ANVIL_PORT (18545) E2E_DB_PORT (15432) — both bound to 127.0.0.1 only; E2E_SKIP_BUILD=1;
#        E2E_KEEP=1 leaves the stack up for debugging (prints the clean-up command).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

E2E_DIR="scripts/e2e-fork"
ENV_FILE="$E2E_DIR/.env.e2e"
PROJECT="kubstake-e2e"
ANVIL_INTERNAL_URL="http://anvil:8545"
export E2E_ANVIL_PORT="${E2E_ANVIL_PORT:-18545}"
export E2E_DB_PORT="${E2E_DB_PORT:-15432}"
TSX="$ROOT/node_modules/.bin/tsx"
DC=(docker compose -p "$PROJECT" --env-file "$ENV_FILE" -f docker-compose.yml -f "$E2E_DIR/docker-compose.fork.yml")

T_START=$(date +%s)
log() { printf '[e2e-fork %s +%ss] %s\n' "$(date +%H:%M:%S)" "$(($(date +%s) - T_START))" "$*"; }
die() {
  printf '[e2e-fork] ERROR: %s\n' "$*" >&2
  exit 1
}

TMP_DIR=""
STARTED=0
cleanup() {
  local rc=$?
  trap - EXIT
  if [ "$STARTED" = 1 ] && [ "$rc" != 0 ]; then
    echo "----- worker logs (last 60 lines) -----" >&2
    "${DC[@]}" logs --no-color --no-log-prefix --tail 60 worker >&2 2>&1 || true
    echo "----- anvil logs (last 40 lines) -----" >&2
    "${DC[@]}" logs --no-color --no-log-prefix --tail 40 anvil >&2 2>&1 || true
  fi
  if [ "${E2E_KEEP:-0}" = 1 ] && [ "$STARTED" = 1 ]; then
    log "E2E_KEEP=1: stack left running. Clean up with:"
    echo "  docker compose -p $PROJECT --env-file $ENV_FILE -f docker-compose.yml -f $E2E_DIR/docker-compose.fork.yml down -v && rm -f $ENV_FILE"
  elif [ -f "$ENV_FILE" ]; then
    log "cleanup: docker compose -p $PROJECT down -v"
    "${DC[@]}" down -v --remove-orphans >/dev/null 2>&1 || "${DC[@]}" down -v --remove-orphans || true
    rm -f "$ENV_FILE"
  fi
  if [ -n "$TMP_DIR" ]; then rm -rf "$TMP_DIR"; fi
  exit "$rc"
}
trap cleanup EXIT
trap 'exit 130' INT TERM

# ---- preflight -------------------------------------------------------------------------------------
command -v docker >/dev/null || die "docker not found"
command -v openssl >/dev/null || die "openssl not found"
command -v node >/dev/null || die "node not found"
[ -x "$TSX" ] || die "tsx not found ($TSX) — run npm install at the repo root first"
docker compose version >/dev/null || die "docker compose v2 not available"

# ---- 1. throwaway secrets + fork settings (never the real .env) ------------------------------------
umask 077
TMP_DIR="$(mktemp -d "${TMPDIR:-/tmp}/kubstake-e2e.XXXXXX")"
PG_PASS="$(openssl rand -hex 24)"
MASTER_KEY="$(openssl rand -base64 32 | tr -d '\n')"
cat >"$ENV_FILE" <<EOF
# GENERATED by scripts/e2e-fork.sh for the anvil-fork e2e only — throwaway values, deleted on exit.
POSTGRES_USER=kubstake
POSTGRES_DB=kubstake_e2e
POSTGRES_PASSWORD=$PG_PASS
MASTER_KEY=$MASTER_KEY
SESSION_SECRET=$(openssl rand -base64 48 | tr -d '\n')
WEB_BIND=127.0.0.1
WEB_PORT=3999
RPC_URL=$ANVIL_INTERNAL_URL
CHAIN_ID=96
SUBGRAPH_URL=
TICK_INTERVAL_SEC=5
RPC_CONCURRENCY=4
LOG_LEVEL=info
GAS_RESERVE_KUB=0.05
MAX_GAS_PRICE_GWEI=50
MIN_INTERVAL_SEC=3600
R_FLOOR_KUB=0.5
CHECK_MIN_SEC=300
CHECK_MAX_SEC=300
VALIDATOR_SYNC_SEC=86400
APP_TIMEZONE=Asia/Bangkok
TZ=Asia/Bangkok
EOF

# ---- 2. SAFETY GUARD: the worker must resolve to the local anvil fork -------------------
"${DC[@]}" config --format json | node -e '
  const c = JSON.parse(require("fs").readFileSync(0, "utf8"));
  const want = process.argv[1];
  const fail = (m) => { console.error("[e2e-fork] SAFETY GUARD: " + m); process.exit(1); };
  const w = (c.services.worker || {}).environment || {};
  if (w.RPC_URL !== want) fail(`worker RPC_URL resolves to "${w.RPC_URL}", expected ${want} — refusing to run a worker that sends real transactions`);
  if (!c.services.anvil) fail("anvil service missing from the merged config");
  const vol = ((c.volumes || {}).pgdata || {}).name;
  if (vol !== "kubstake-e2e_pgdata") fail(`db volume resolves to "${vol}", expected kubstake-e2e_pgdata`);
  if (c.name !== "kubstake-e2e") fail(`compose project resolves to "${c.name}"`);
  console.log(`[e2e-fork] guard OK: project ${c.name}, worker RPC_URL=${w.RPC_URL}, volume ${vol}`);
' "$ANVIL_INTERNAL_URL"

# leftovers of an interrupted run (this project only)
"${DC[@]}" down -v --remove-orphans >/dev/null 2>&1 || true
STARTED=1

# ---- 3. image, db, migrate (before anvil: the fork's clock starts when anvil starts) -----------------
if [ "${E2E_SKIP_BUILD:-0}" != 1 ]; then
  log "building worker image kubstake-worker:e2e (cached layers make this fast after the first build)"
  "${DC[@]}" build worker
fi
log "starting db + migrate"
"${DC[@]}" up -d db migrate
MIGRATE_CID="$("${DC[@]}" ps -a -q migrate)"
[ -n "$MIGRATE_CID" ] || die "migrate container not found"
migrate_state=""
for _ in $(seq 1 120); do
  migrate_state="$(docker inspect -f '{{.State.Status}} {{.State.ExitCode}}' "$MIGRATE_CID")"
  case "$migrate_state" in
    "exited 0") break ;;
    exited*)
      "${DC[@]}" logs --no-color migrate >&2 || true
      die "migrate failed ($migrate_state)"
      ;;
  esac
  sleep 1
done
[ "$migrate_state" = "exited 0" ] || die "migrate did not finish within 120s ($migrate_state)"
log "migrate exited 0"

# ---- 4. anvil fork --------------------------------------------------------------------------------
log "starting anvil fork of KUB mainnet (127.0.0.1:$E2E_ANVIL_PORT)"
T_FORK=$(date +%s)
"${DC[@]}" up -d --wait --wait-timeout 120 anvil

export E2E_RPC_URL="http://127.0.0.1:$E2E_ANVIL_PORT"
export E2E_DATABASE_URL="postgres://kubstake:$PG_PASS@127.0.0.1:$E2E_DB_PORT/kubstake_e2e"
export E2E_MASTER_KEY="$MASTER_KEY"
export E2E_STATE_FILE="$TMP_DIR/state.json"

log "seed: validator 0 + throwaway wallet + position"
"$TSX" "$E2E_DIR/setup.ts" seed

# ---- 5. worker (second guard: its own startup line must name the anvil RPC) -------------------------
log "starting worker (RPC anvil:8545)"
"${DC[@]}" up -d --no-deps worker
ready=0
for _ in $(seq 1 90); do
  wlogs="$("${DC[@]}" logs --no-color --no-log-prefix worker 2>/dev/null || true)"
  start_line="$(grep '"msg":"worker starting"' <<<"$wlogs" | tail -1 || true)"
  if [ -n "$start_line" ]; then
    if ! grep -q '"rpc":"anvil:8545"' <<<"$start_line"; then
      "${DC[@]}" kill worker >/dev/null 2>&1 || true
      die "SAFETY GUARD: worker started with an unexpected RPC: $start_line"
    fi
  fi
  if grep -q 'leader lock acquired' <<<"$wlogs"; then
    ready=1
    break
  fi
  if [ "$(docker inspect -f '{{.State.Running}}' "$("${DC[@]}" ps -a -q worker)" 2>/dev/null)" != true ]; then
    die "worker container is not running"
  fi
  sleep 1
done
[ "$ready" = 1 ] || die "worker did not acquire the leader lock within 90s"
log "worker ready (chainId 96 OK via anvil, leader lock acquired)"

# ---- 6. flow + assert -------------------------------------------------------------------------------
"$TSX" "$E2E_DIR/setup.ts" flow
"$TSX" "$E2E_DIR/assert.ts"

errors="$("${DC[@]}" logs --no-color --no-log-prefix worker 2>/dev/null | grep -cE '"level":"(error|fatal)"' || true)"
log "worker error/fatal log lines: $errors · fork age at the end: $(($(date +%s) - T_FORK))s · total $(($(date +%s) - T_START))s"
echo "E2E OK"
